// Shared-member CRUD matrix: one person, every sign-in method (phone demo OTP, email+password with the in-memory
// mail outbox as the SMTP catcher, Google + Apple with mocked token exchange/JWKS, native-wrapper deep link with
// PKCE verifier). Sign in via A → write → sign out → sign in via B → read back identical → B updates/deletes →
// sign in via A → confirm. Results go to CRUD_MATRIX.md (path from CRUD_MATRIX_OUT).
import { test, before, after } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import { createHash, randomBytes } from "node:crypto";
import { setTestEnv, startApp, startMockProviders, wipeDb, api, phoneLogin, wsClient, oauthRoundTrip, type App, type MockProviders } from "./harness";

const keys = setTestEnv({ providers: true })!;
let app: App, mock: MockProviders;
let outbox: { to: string; subject: string; link?: string }[];
let resetRateLimits: () => void;
const uniq = () => randomBytes(4).toString("hex");
const results = new Map<string, Map<string, boolean>>();
const OPS = ["sign in → same user id", "profile name/bio", "avatar", "social links", "follows", "DMs", "room created", "notification prefs", "update/delete by other method", "logout revokes", "refresh rotates", "re-sign-in sees changes"];
const mark = (m: string, op: string, ok: boolean) => (results.get(m) ?? results.set(m, new Map()).get(m)!).set(op, ok);
const check = (m: string, op: string, fn: () => void) => { try { fn(); mark(m, op, true); } catch (e) { mark(m, op, false); throw e; } };

before(async () => {
  await wipeDb();
  mock = await startMockProviders({ googleClientId: process.env.GOOGLE_CLIENT_ID!, googleSecret: process.env.GOOGLE_CLIENT_SECRET!, appleServicesId: process.env.APPLE_SERVICES_ID!, appleTeamId: process.env.APPLE_TEAM_ID!, appleKeyId: process.env.APPLE_KEY_ID!, applePublicKey: keys.applePublicKey });
  const providers = await import("../../server/authx/providers");
  providers.__setProviderEndpoints({
    google: { authUrl: `${mock.url}/google/auth`, tokenUrl: `${mock.url}/google/token`, jwksUrl: `${mock.url}/google/jwks`, issuers: ["https://accounts.google.com"] },
    apple: { authUrl: `${mock.url}/apple/auth`, tokenUrl: `${mock.url}/apple/token`, jwksUrl: `${mock.url}/apple/jwks`, issuers: ["https://appleid.apple.com"] },
  });
  outbox = (await import("../../server/authx/mailer")).outbox;
  resetRateLimits = (await import("../../server/authx/ratelimit")).resetRateLimits;
  app = await startApp();
});
after(async () => {
  const out = process.env.CRUD_MATRIX_OUT;
  if (out) {
    const methods = [...results.keys()];
    let md = `# Shared-member CRUD matrix\n\nGenerated by tests/unified-auth/member-matrix.test.ts on ${new Date().toISOString()} (local Postgres, mocked Google/Apple, in-memory mail outbox, demo phone OTP 000000).\n\n| Operation | ${methods.join(" | ")} |\n|---|${methods.map(() => "---").join("|")}|\n`;
    for (const op of OPS) md += `| ${op} | ${methods.map((m) => (results.get(m)!.has(op) ? (results.get(m)!.get(op) ? "PASS" : "FAIL") : "n/a")).join(" | ")} |\n`;
    md += `\nNot applicable in this app (no server feature exists): DM delete, room RSVP, account deletion. Theme is device-local. The wrapper deep-link column only checks sign-in/refresh/logout and identity (its CRUD is the same session type as Google).\n`;
    fs.writeFileSync(out, md);
  }
  await Promise.race([Promise.all([app?.close(), mock?.close()]), new Promise((r) => setTimeout(r, 3000))]);
});

test("one member across phone / email / Google / Apple / native deep link", async () => {
  resetRateLimits();
  const phone = `+1415${Math.floor(1_000_000 + Math.random() * 8_999_999)}`;
  const email = `donny_${uniq()}@example.com`, pw = "matrix-pass-1";
  const gsub = "g-" + uniq(), asub = "001." + uniq();
  const verifier = randomBytes(32).toString("base64url");
  const cc = createHash("sha256").update(verifier).digest("base64url");

  // the member is created by phone (demo OTP), then links every other method from Settings
  const first = await phoneLogin(app.wsUrl, phone, { firstName: "Donny", username: `donny_${uniq()}` });
  const uid = first.res.user.id as string;
  const friend = await phoneLogin(app.wsUrl, `+1415${Math.floor(1_000_000 + Math.random() * 8_999_999)}`, { firstName: "Fran", username: `fran_${uniq()}` });
  const fid = friend.res.user.id as string;
  let tok = first.res.access as string;
  await api(app.base, "/auth/email/link", { email, password: pw }, { token: tok });
  const link = [...outbox].reverse().find((m) => m.to === email)!.link!;
  assert.equal((await api(app.base, "/auth/email/verify", { token: new URL(link).searchParams.get("token") })).data.status, "linked");
  for (const [p, sub] of [["google", gsub], ["apple", asub]] as const) {
    const st = await api(app.base, "/auth/link/start", { provider: p }, { token: tok });
    const r = await oauthRoundTrip(app, mock, p, { sub, email: `${p}_${uniq()}@example.com`, email_verified: true }, { query: st.data.url.split("?")[1] });
    assert.equal(r.stage === "exchange" && r.exchange.data.status, "linked");
  }
  const ids = (await api(app.base, "/auth/identities", undefined, { token: tok })).data.identities.map((i: { provider: string }) => i.provider).sort();
  assert.deepEqual(ids, ["apple", "email", "google", "phone"]);
  first.client.close();

  const signIn: Record<string, () => Promise<{ access: string; refresh: string; userId: string }>> = {
    "Phone (demo OTP)": async () => { const r = await phoneLogin(app.wsUrl, phone); r.client.close(); return { access: r.res.access, refresh: r.res.refresh, userId: r.res.user.id }; },
    "Phone (Firebase, mocked token)": async () => { const r = await api(app.base, "/api/auth/firebase", { idToken: "matrix-fb-token" }); assert.equal(r.data.status, "existing"); return { access: r.data.access, refresh: r.data.refresh, userId: r.data.user?.id }; },
    "Email + password": async () => { const r = await api(app.base, "/auth/email/login", { email, password: pw }); return { access: r.data.access, refresh: r.data.refresh, userId: r.data.user?.id }; },
    "Google (mocked)": async () => { const r = await oauthRoundTrip(app, mock, "google", { sub: gsub, email_verified: true }); assert.equal(r.stage, "exchange"); const d = (r as any).exchange.data; return { access: d.access, refresh: d.refresh, userId: d.user?.id }; },
    "Apple (mocked)": async () => { const r = await oauthRoundTrip(app, mock, "apple", { sub: asub }); assert.equal(r.stage, "exchange"); const d = (r as any).exchange.data; return { access: d.access, refresh: d.refresh, userId: d.user?.id }; },
    "Wrapper deep link (Google app=1)": async () => { const r = await oauthRoundTrip(app, mock, "google", { sub: gsub }, { query: `app=1&cc=${cc}`, codeVerifier: verifier }); assert.match((r as any).location, /^openlounge:\/\/auth\?code=/); const d = (r as any).exchange.data; return { access: d.access, refresh: d.refresh, userId: d.user?.id }; },
  };
  const fb = await import("../../server/firebase");
  fb.setPhoneVerifier(async (tok) => (tok === "matrix-fb-token" ? { ok: true, phone, uid: "fb-matrix" } : { ok: false, error: "bad" }));
  const methods = Object.keys(signIn);
  const ws = async (access: string) => { const c = wsClient(app.wsUrl); await c.open; const r = await c.req("session:resume", { token: access }); assert.equal(r.ok, true); return c; };
  const png = "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==";

  const { store } = await import("../../server/store");
  (await import("../../server/push")).initPush();
  for (let i = 0; i < methods.length; i++) {
    resetRateLimits();
    (store as unknown as { socialRate: Map<string, number[]> }).socialRate.clear(); // per-user 10 saves/min limit
    const A = methods[i], B = methods[(i + 1) % methods.length];
    const tag = `${i}-${uniq()}`;
    // ---- sign in via A, write
    let s = await signIn[A]();
    check(A, "sign in → same user id", () => assert.equal(s.userId, uid));
    let c = await ws(s.access);
    assert.equal((await c.req("user:update", { name: `Donny ${tag}`, bio: `bio from ${A}` })).ok, true);
    assert.equal((await c.req("user:photo", { photo: png })).ok, true);
    const sl = await api(app.base, "/api/me/social-links", { links: { instagram: `donny${i}`, website: `https://donny${i}.example.com` } }, { token: s.access });
    assert.equal(sl.status, 200);
    assert.equal((await c.req("user:follow", { userId: fid, follow: true })).ok, true);
    assert.equal((await c.req("dm:send", { to: fid, text: `dm via ${A} ${tag}` })).ok, true);
    const prefSet = await api(app.base, "/api/notifications/prefs", { dm: i % 2 === 0, quietHours: { start: "22:00", end: `0${i}:30`, tz: "America/Phoenix" } }, { token: s.access });
    const room = await c.req("room:create", { title: `Room ${tag}`, topic: "Tech" });
    // refresh rotation for this method's session
    const rf = await api(app.base, "/auth/refresh", { refreshToken: s.refresh });
    check(A, "refresh rotates", () => { assert.equal(rf.status, 200); assert.notEqual(rf.data.refresh, s.refresh); });
    // the new access token works; the old refresh token is only honoured inside ROTATION_GRACE_MS (lost-response
    // recovery, by design) — reuse after the window revokes the session (covered in unit tests)
    check(A, "refresh rotates", () => assert.ok(rf.data.access));
    assert.equal((await api(app.base, "/auth/validate", undefined, { token: rf.data.access })).status, 200);
    if (room.ok && room.roomId) await c.req("room:end", { roomId: room.roomId }).catch(() => null);
    c.close();
    // ---- sign out
    const sNew = (await signIn[A]()); // a session that the reuse-detection didn't kill
    await api(app.base, "/auth/logout", {}, { token: sNew.access });
    const dead = await api(app.base, "/auth/validate", undefined, { token: sNew.access });
    check(A, "logout revokes", () => assert.equal(dead.status, 401));

    // ---- sign in via B, read back
    const sb = await signIn[B]();
    assert.equal(sb.userId, uid);
    const cb = await ws(sb.access);
    const v = (await api(app.base, "/auth/validate", undefined, { token: sb.access })).data;
    const prof = (await cb.req("user:get", { userId: uid })).profile;
    check(A, "profile name/bio", () => { assert.equal(v.user.name, `Donny ${tag}`); assert.equal(v.user.bio, `bio from ${A}`); });
    check(A, "avatar", () => assert.ok(v.user.photoVersion || prof.user.photoVersion || v.user.photoUrl));
    check(A, "social links", () => assert.equal((v.user.socialLinks ?? prof.user.socialLinks).instagram, `https://instagram.com/donny${i}`));
    check(A, "follows", () => assert.ok(v.following.includes(fid)));
    const hist = (await cb.req("dm:history", { peerId: fid })).messages.map((m: { text: string }) => m.text);
    check(A, "DMs", () => assert.ok(hist.includes(`dm via ${A} ${tag}`)));
    check(A, "room created", () => assert.equal(room.ok, true));
    const prefGet = await api(app.base, "/api/notifications/prefs", undefined, { token: sb.access });
    check(A, "notification prefs", () => { assert.equal(prefSet.status, 200, JSON.stringify(prefSet.data)); assert.equal(prefGet.data.prefs.quietHours?.end, `0${i}:30`); assert.equal(prefGet.data.prefs.dm, i % 2 === 0); });
    // ---- B updates / deletes
    await cb.req("user:update", { bio: "" });
    await cb.req("user:photo", { photo: null });
    await api(app.base, "/api/me/social-links", { links: { website: null } }, { token: sb.access });
    await cb.req("user:follow", { userId: fid, follow: false });
    cb.close();
    await api(app.base, "/auth/logout", {}, { token: sb.access });

    // ---- back via A: changes stuck
    s = await signIn[A]();
    const back = (await api(app.base, "/auth/validate", undefined, { token: s.access })).data;
    check(A, "update/delete by other method", () => {
      assert.equal(back.user.id, uid);
      assert.equal(back.user.bio, "");
      assert.ok(!back.user.photoVersion);
      assert.equal(back.user.socialLinks?.website, undefined);
      assert.equal(back.user.socialLinks?.instagram, `https://instagram.com/donny${i}`);
      assert.ok(!back.following.includes(fid));
    });
    const c2 = await ws(s.access);
    const h2 = (await c2.req("dm:history", { peerId: fid })).messages.map((m: { text: string }) => m.text);
    check(A, "re-sign-in sees changes", () => { for (let j = 0; j <= i; j++) assert.ok(h2.includes(`dm via ${methods[j]} ${j}-` ) || h2.some((t: string) => t.startsWith(`dm via ${methods[j]} ${j}-`))); });
    c2.close();
    await api(app.base, "/auth/logout", {}, { token: s.access });
  }
  friend.client.close();
  fb.setPhoneVerifier(null);
});

test("real phone verified later (Firebase) links to the existing member; demo codes can't link once demo OTP is off", async () => {
  resetRateLimits();
  const fb = await import("../../server/firebase");
  const phone = `+1415${Math.floor(1_000_000 + Math.random() * 8_999_999)}`;
  fb.setPhoneVerifier(async (tok) => (tok === "fb-good-token" ? { ok: true, phone, uid: "fb-1" } : { ok: false, error: "bad" }));
  try {
    // an email member (created via the in-memory SMTP outbox)
    const email = `later_${uniq()}@example.com`;
    await api(app.base, "/auth/email/signup", { email, password: "later-pass-1" });
    const link = [...outbox].reverse().find((m) => m.to === email)!.link!;
    const v = await api(app.base, "/auth/email/verify", { token: new URL(link).searchParams.get("token") });
    const c = wsClient(app.wsUrl);
    await c.open;
    const reg = await c.req("auth:register", { ticket: v.data.ticket, firstName: "Lia", lastName: "", username: `lia_${uniq()}`, bio: "", color: "#22C55E", interests: [] });
    assert.equal(reg.ok, true);
    const uid = reg.user.id;
    assert.equal((await c.req("account:linkPhoneFirebase", { idToken: "nope" })).ok, false);
    const linked = await c.req("account:linkPhoneFirebase", { idToken: "fb-good-token" });
    assert.equal(linked.ok, true, JSON.stringify(linked));
    c.close();
    // Firebase phone sign-in on a fresh device → the same member
    const r = await api(app.base, "/api/auth/firebase", { idToken: "fb-good-token" });
    assert.equal(r.status, 200, JSON.stringify(r.data));
    assert.equal(r.data.status, "existing");
    assert.equal(r.data.user.id, uid);
    // with demo OTP disabled, a demo code can't attach someone else's number
    process.env.DEMO_OTP_ENABLED = "0";
    const c2 = wsClient(app.wsUrl);
    await c2.open;
    await c2.req("session:resume", { token: r.data.access });
    const bad = await c2.req("account:linkPhone", { phone: "+14155550999", code: "000000" });
    assert.equal(bad.ok, false);
    c2.close();
  } finally {
    delete process.env.DEMO_OTP_ENABLED;
    fb.setPhoneVerifier(null);
  }
});
